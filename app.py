def initialize_exam_state(exam_id):
    key = f"submitted_{exam_id}"
    if key not in st.session_state:
        st.session_state[key] = False


def render_quiz(questions, quiz_id):
    """단원별 퀴즈"""
    st.subheader("📝 단원 확인 퀴즈")

    if f"quiz_submitted_{quiz_id}" not in st.session_state:
        st.session_state[f"quiz_submitted_{quiz_id}"] = False

    for i, q in enumerate(questions):
        st.radio(
            f"{i + 1}. {q['question']}",
            q["options"],
            key=f"{quiz_id}_q_{i}",
            index=None,
        )

    col1, col2 = st.columns(2)

    with col1:
        if st.button("채점하기", key=f"submit_{quiz_id}", use_container_width=True):
            unanswered = [
                i + 1
                for i, q in enumerate(questions)
                if st.session_state.get(f"{quiz_id}_q_{i}") is None
            ]
            if unanswered:
                st.warning(
                    "답하지 않은 문제가 있습니다: "
                    + ", ".join(map(str, unanswered))
                    + "번"
                )
            else:
                st.session_state[f"quiz_submitted_{quiz_id}"] = True

    with col2:
        if st.button("다시 풀기", key=f"reset_{quiz_id}", use_container_width=True):
            for i in range(len(questions)):
                st.session_state.pop(f"{quiz_id}_q_{i}", None)
            st.session_state[f"quiz_submitted_{quiz_id}"] = False
            st.rerun()

    if st.session_state[f"quiz_submitted_{quiz_id}"]:
        score = 0
        for i, q in enumerate(questions):
            selected = st.session_state.get(f"{quiz_id}_q_{i}")
            if selected == q["options"][q["answer"]]:
                score += 1

        st.success(f"점수: {score} / {len(questions)}")

        for i, q in enumerate(questions):
            selected = st.session_state.get(f"{quiz_id}_q_{i}")
            correct = q["options"][q["answer"]]

            if selected == correct:
                st.markdown(f"**{i + 1}번: 정답 ✅**")
            else:
                st.markdown(
                    f"**{i + 1}번: 오답 ❌**  \n"
                    f"- 선택: {selected}  \n"
                    f"- 정답: {correct}"
                )
            st.caption(q["explanation"])


def render_exam(exam, exam_id):
    """30문항 시험지"""
    initialize_exam_state(exam_id)

    st.info(
        "각 문항의 답을 고른 뒤 맨 아래의 채점 버튼을 누르세요. "
        "시험지는 모두 객관식 4지선다형입니다."
    )

    for i, q in enumerate(exam):
        st.radio(
            f"{i + 1}. {q['question']}",
            q["options"],
            key=f"{exam_id}_question_{i}",
            index=None,
        )
        st.divider()

    col1, col2 = st.columns(2)

    with col1:
        if st.button(
            "시험지 채점하기",
            key=f"{exam_id}_submit",
            type="primary",
            use_container_width=True,
        ):
            unanswered = [
                i + 1
                for i in range(len(exam))
                if st.session_state.get(f"{exam_id}_question_{i}") is None
            ]
            if unanswered:
                st.warning(
                    "답하지 않은 문항: "
                    + ", ".join(map(str, unanswered))
                    + "번"
                )
            else:
                st.session_state[f"submitted_{exam_id}"] = True

    with col2:
        if st.button(
            "답안 초기화",
            key=f"{exam_id}_reset",
            use_container_width=True,
        ):
            for i in range(len(exam)):
                st.session_state.pop(f"{exam_id}_question_{i}", None)
            st.session_state[f"submitted_{exam_id}"] = False
            st.rerun()

    if st.session_state[f"submitted_{exam_id}"]:
        score = 0
        wrong_numbers = []

        for i, q in enumerate(exam):
            selected = st.session_state.get(f"{exam_id}_question_{i}")
            correct = q["options"][q["answer"]]
            if selected == correct:
                score += 1
            else:
                wrong_numbers.append(i + 1)

        percent = round(score / len(exam) * 100, 1)

        st.header("📊 채점 결과")
        c1, c2, c3 = st.columns(3)
        c1.metric("정답 수", f"{score} / {len(exam)}")
        c2.metric("점수", f"{percent}점")
        c3.metric("오답 수", len(wrong_numbers))

        if percent >= 90:
            st.success("매우 훌륭합니다! 개념을 정확하게 이해하고 있습니다.")
        elif percent >= 80:
            st.success("잘했습니다! 틀린 문항의 개념만 다시 확인해 보세요.")
        elif percent >= 60:
            st.warning("기본 개념은 알고 있지만 일부 단원의 복습이 필요합니다.")
        else:
            st.error("개념 학습 페이지를 다시 읽은 뒤 재도전해 보세요.")

        if wrong_numbers:
            st.write("오답 문항:", ", ".join(map(str, wrong_numbers)))
        else:
            st.balloons()

        with st.expander("정답 및 해설 확인", expanded=True):
            for i, q in enumerate(exam):
                selected = st.session_state.get(f"{exam_id}_question_{i}")
                correct = q["options"][q["answer"]]

                if selected == correct:
                    st.markdown(f"### {i + 1}번 ✅")
                else:
                    st.markdown(f"### {i + 1}번 ❌")

                st.write("정답:", correct)
                st.write("내 답:", selected)
                st.caption(q["explanation"])
                st.divider()


def q(question, options, answer, explanation):
    return {
        "question": question,
        "options": options,
        "answer": answer,
        "explanation": explanation,
    }


